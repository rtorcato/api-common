// Generate the subpath table in README.md and packages/api-common/README.md from
// packages/api-common/subpaths.json, so the tables can't drift when a subpath is
// added or its description changes. subpaths.json is the single source of truth;
// a package test keeps it in step with the `exports` map.
//
//   node scripts/gen-readme-packages.mjs          # rewrite the tables in place
//   node scripts/gen-readme-packages.mjs --check   # exit 1 if a README is stale (CI)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const pkgDir = resolve(repoRoot, 'packages/api-common')
const readmes = [resolve(repoRoot, 'README.md'), resolve(pkgDir, 'README.md')]

const START = '<!-- PACKAGES:START - generated by scripts/gen-readme-packages.mjs -->'
const END = '<!-- PACKAGES:END -->'

const pkg = JSON.parse(readFileSync(resolve(pkgDir, 'package.json'), 'utf8'))
const subpaths = JSON.parse(readFileSync(resolve(pkgDir, 'subpaths.json'), 'utf8'))

const rows = subpaths.map(
	(s) => `| \`${pkg.name}/${s.subpath}\` | \`${s.formerly}\` | ${s.description ?? ''} |`
)

const table = [
	START,
	'| Import | Replaces | Description |',
	'| --- | --- | --- |',
	...rows,
	END,
].join('\n')

const region = new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`)
const check = process.argv.includes('--check')
let stale = false

for (const path of readmes) {
	const readme = readFileSync(path, 'utf8')
	if (!region.test(readme)) {
		console.error(`${path} is missing the ${START} ... ${END} markers.`)
		process.exit(1)
	}
	const next = readme.replace(region, table)
	if (check) {
		if (next !== readme) {
			console.error(`${path}: subpath table is out of date. Run \`pnpm gen:readme\`.`)
			stale = true
		}
	} else {
		writeFileSync(path, next)
		console.log(`Wrote ${subpaths.length} subpaths to ${path}.`)
	}
}

if (check) {
	if (stale) process.exit(1)
	console.log('README subpath tables are up to date.')
}

function escapeRe(s) {
	return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
